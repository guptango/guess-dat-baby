export const getCoupleString = (mom: string, dad: string) => {
    return `${mom} & ${dad}`
}

export const getCoupleFromString = (coupleString: string) => {
    if (!coupleString) {
        return { mom: '', dad: '' }
    }
    const [mom, dad] = coupleString.split(' & ')
    return { mom: mom || '', dad: dad || '' }
}

